//! The study registry's module list (crate::registry): every `src/studies/*.rs` becomes a crate-root
//! module (`crate::<file stem>`), and its `STUDY` joins `STUDY_DEFS`, in file name order. A new
//! study is one new file there; no shared file names it.

use std::fmt::Write as _;
use std::path::Path;

fn main() {
    let dir = Path::new(&std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR")).join("src/studies");
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut stems: Vec<(String, String)> = Vec::new();
    for e in std::fs::read_dir(&dir).unwrap_or_else(|e| panic!("reading {}: {e}", dir.display())) {
        let p = e.expect("a directory entry").path();
        if p.extension().is_some_and(|x| x == "rs") {
            println!("cargo:rerun-if-changed={}", p.display());
            let stem = p.file_stem().and_then(|s| s.to_str()).expect("a UTF-8 file name").to_string();
            assert!(stem.chars().all(|c| c.is_ascii_lowercase() || c.is_ascii_digit() || c == '_'), "src/studies/{stem}.rs: a study file is named like a module (a-z, 0-9, _)");
            stems.push((stem, p.display().to_string()));
        }
    }
    stems.sort();
    let mut out = String::from("// GENERATED by crates/circuit/build.rs from src/studies/*.rs: do not edit.\n\n");
    for (stem, path) in &stems {
        writeln!(out, "#[path = {path:?}]\npub mod {stem};").unwrap();
    }
    writeln!(out, "\n/// Every study module's registration (`src/studies/*.rs`, in file name order).").unwrap();
    writeln!(out, "pub static STUDY_DEFS: &[&crate::registry::StudyDef] = &[{}];", stems.iter().map(|(s, _)| format!("&{s}::STUDY")).collect::<Vec<_>>().join(", ")).unwrap();
    let to = Path::new(&std::env::var("OUT_DIR").expect("OUT_DIR")).join("studies.rs");
    std::fs::write(&to, out).unwrap_or_else(|e| panic!("writing {}: {e}", to.display()));
}
