//! The item registry's module list (`redstone::container`): every `pub const MODULE_ITEMS: &[(&str,
//! u8)]` in `src/**/*.rs` joins `MODULE_ITEMS_ALL`, in module path order. A study's new items go
//! in such a list in its own module; no shared file names them.

use std::fmt::Write as _;
use std::path::{Path, PathBuf};

const MARK: &str = "pub const MODULE_ITEMS: &[(&str, u8)]";

fn walk(dir: &Path, out: &mut Vec<PathBuf>) {
    println!("cargo:rerun-if-changed={}", dir.display());
    let mut entries: Vec<PathBuf> = std::fs::read_dir(dir).unwrap_or_else(|e| panic!("reading {}: {e}", dir.display())).map(|e| e.expect("a directory entry").path()).collect();
    entries.sort();
    for p in entries {
        if p.is_dir() {
            walk(&p, out);
        } else if p.extension().is_some_and(|x| x == "rs") {
            out.push(p);
        }
    }
}

fn main() {
    let src = Path::new(&std::env::var("CARGO_MANIFEST_DIR").expect("CARGO_MANIFEST_DIR")).join("src");
    let mut files = Vec::new();
    walk(&src, &mut files);
    let mut modules: Vec<String> = Vec::new();
    for f in &files {
        println!("cargo:rerun-if-changed={}", f.display());
        let text = std::fs::read_to_string(f).unwrap_or_else(|e| panic!("reading {}: {e}", f.display()));
        if !text.lines().any(|l| l.trim_start().starts_with(MARK)) {
            continue;
        }
        let rel = f.strip_prefix(&src).expect("under src");
        let mut parts: Vec<String> = rel.with_extension("").iter().map(|s| s.to_str().expect("a UTF-8 path").to_string()).collect();
        if parts.last().is_some_and(|l| l == "mod" || l == "lib") {
            parts.pop();
        }
        modules.push(std::iter::once("crate".to_string()).chain(parts).collect::<Vec<_>>().join("::"));
    }
    modules.sort();
    let mut out = String::from("// GENERATED by crates/redsim/build.rs from every `MODULE_ITEMS` list: do not edit.\n\n");
    writeln!(out, "/// Every module's `MODULE_ITEMS` (build.rs), in module path order.").unwrap();
    writeln!(out, "pub static MODULE_ITEMS_ALL: &[&[(&str, u8)]] = &[{}];", modules.iter().map(|m| format!("{m}::MODULE_ITEMS")).collect::<Vec<_>>().join(", ")).unwrap();
    let to = Path::new(&std::env::var("OUT_DIR").expect("OUT_DIR")).join("module_items.rs");
    std::fs::write(&to, out).unwrap_or_else(|e| panic!("writing {}: {e}", to.display()));
}
